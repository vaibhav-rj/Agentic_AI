'''
The important distinction is:

Required = must exist when the graph starts.
NotRequired = legitimately absent initially and populated later.
''' 
class QuantPilotState(TypedDict):
    """Shared state passed between QuantPilot graph nodes."""

    # Required inputs supplied when the graph starts
    user_query: str
    ticker: str
    start: date
    end: date

    # Optional input; only needed for financial research
    financial_metrics: NotRequired[list[str]]

    # Generated during workflow execution
    research_query: NotRequired[ResearchQuery]
    research_plan: NotRequired[ResearchPlan]

    #Generated during replan workflow exceution
    replan_plan: NotRequired[ResearchPlan]
    replan_financial_metrics: NotRequired[list[str]]
    replan_count: NotRequired[int]

    #after plan_replan generation 
    research_results: NotRequired[list[dict]]

    # Generated by later research stages
    evidence: NotRequired[EvidenceLedger]
    thesis: NotRequired[Thesis]
    critique: NotRequired[Critique]
    adjudication: NotRequired[Adjudication]
    final_report: NotRequired[FinalReport]
