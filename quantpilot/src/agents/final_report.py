#refinement of summary and conclusion
def _refine_report_narrative(
    user_query: str,
    thesis: str,
    conclusion: str,
    normalized_results: list[dict],
    limitations: list[str],
) -> tuple[str, str]:
    try:
        messages = [
            SystemMessage(content=(
               "Refine the financial research report's summary and conclusion. "
                "Use exclusively the supplied information; never invent facts, "
                "figures, comparisons, or conclusions. "
                "The summary must concisely answer the user's query and accurately "
                "represent the supplied thesis(fallback summary) and normalized results. "
                "The conclusion must faithfully explain the fallback/input conclusion(adjudication rationale) "
                "and remain consistent with the evidence and stated limitations(adjudication evidence_debt). "
                "Distinguish synthesized external research from measured evidence "
                "provided by structured market, financial, and quantitative tools. "
                "Assess external research for relevance, reliability, temporal coverage, "
                "and independent corroboration. Do not treat general external research "
                "as direct validation of measured market performance or valuation. "
                "Distinguish measured results from interpretations and acknowledge "
                "material evidence gaps, limited sample sizes, and weak external "
                "research where relevant. "
                "Do not overstate certainty or imply unsupported comparative conclusions. "
                "Treat duplicate copies of the same underlying evidence as one fact, "
                "not independent corroboration. "
                "Do not alter the underlying adjudication, confidence, evidence, "
                "or limitations. "
                "Keep both fields concise, coherent, and complete regarding material "
                "findings and limitations. Do not exceed 512 output tokens. "
                "Return valid JSON only, with exactly these two string fields: "
                '{"summary":"...", "conclusion":"..."} '
                "Do not include Markdown or additional commentary."
            )),
            HumanMessage(content=json.dumps({
                "user_query": user_query,
                "thesis": thesis,
                "conclusion": conclusion,
                "normalized_results": normalized_results,
                "limitations": limitations,
            }, ensure_ascii=False, default=str)),
        ]

        response = invoke_with_fallback("reasoning", messages)
        logger.info("Final report summary and conclusion response generated by LLM" )

        if not isinstance(response.content, str):
            raise ValueError("Invalid LLM response")

        result = json.loads(response.content)
        summary = result.get("summary")
        refined_conclusion = result.get("conclusion")

        if not (
            isinstance(summary, str) and summary.strip()
            and isinstance(refined_conclusion, str)
            and refined_conclusion.strip()
        ):
            raise ValueError("Invalid report narrative")

        return summary.strip(), refined_conclusion.strip()

    except Exception:
        logger.warning("LLM summary & conslusion generation failed; using heuristic fallback", exc_info=True)
        return thesis, conclusion

#to split the ressearch_results(exceutor o/p of both plan and replan run from consolidated)
def _split_results(
    results: list[dict],
) -> tuple[list[dict], list[dict]]:
    split_points = []

    for i in range(1, len(results)):
        previous_id = results[i - 1].get("step_id")
        current_id = results[i].get("step_id")

        if previous_id is None or current_id is None:
            raise ValueError("Every execution result must have a step_id.")

        if current_id <= previous_id:
            split_points.append(i)

    if len(split_points) > 1:
        print("DEBUG step_ids:", [item.get("step_id") for item in results])#diagnosis patch
        print("DEBUG split_points:", split_points)#diagnosis patch

        raise ValueError("Unexpected multiple execution-batch resets.")

    if not split_points:
        return results, []

    split_at = split_points[0]
    return results[:split_at], results[split_at:]


#check plan/replan o/p against theur splitted results and merge the fileds of both if positive match overall
def _align_results(results: list[dict], plan) -> list[dict]:
    if len(results) != len(plan.steps):
        raise ValueError(
            "Execution result count does not match its plan."
        )

    aligned = []

    for step, result in zip(plan.steps, results):
        if (
            result.get("step_id") != step.step_id
            or result.get("tool_category") != step.tool_category
            or result.get("task_type") != step.task_type
        ):
            raise ValueError(
                f"Execution result does not match plan step {step.step_id}."
            )

        aligned.append({
            **result,
            "objective": step.objective,
            "required": step.required,
        })

    return aligned

#to fiter out successful/un-successful results
def _successful(result: dict) -> bool:
    output = result.get("result")

    if output is None or output == {}:
        return False

    if isinstance(output, dict):
        if output.get("error"):
            return False

        if str(output.get("status", "")).lower() in {
            "failed", "failure", "error"
        }:
            return False

    return True

#extract financial metroc names from specific results(one whose tool_cate='financial')
def _metric_names(result: dict | None) -> set[str]:
    if not isinstance(result, dict):
        return set()

    metrics = result.get("metrics", [])

    if not isinstance(metrics, list):
        return set()

    return {
        metric["name"]
        for metric in metrics
        if isinstance(metric, dict) and isinstance(metric.get("name"), str)
    }

#normalization of consolidated results(map many task_type with theor same tool_cat and its result)
def _normalize_results(
    initial: list[dict],
    replan: list[dict],
    financial_metrics: list[str] | None = None,
    replan_financial_metrics: list[str] | None = None,
) -> dict[str, dict]:
    
    grouped: dict[str, dict] = {}

    for batch_name, batch in (
        ("initial", initial),
        ("replan", replan),
    ):
        for item in batch:
            category = item["tool_category"]

            #dict(category-->intnetded dict_value{4 filels})---> doesn't create duplicate 
            # key again if key already created===>used here to grp dict(4 keys by category)
            entry = grouped.setdefault(category, {
                "task_types": [],
                #"plan_context": [],
                "initial": [],
                "replan": [],
            })

            if item["task_type"] not in entry["task_types"]:
                entry["task_types"].append(item["task_type"])

            '''
            context = {
                "task_type": item["task_type"],
                "objective": item["objective"],
                "required": item["required"],
            }
            if context not in entry["plan_context"]:
                entry["plan_context"].append(context)
            '''

            entry[batch_name].append(item)

    normalized = {}

    for category, entry in grouped.items():
        initial_ok = [
            item for item in entry["initial"] if _successful(item)
        ]
        replan_ok = [
            item for item in entry["replan"] if _successful(item)
        ]

        chosen = initial_ok[-1] if initial_ok else None

        if category == "financial" and replan_ok:
            candidate = replan_ok[-1]
            expected = set(financial_metrics or []) | set(
                replan_financial_metrics or []
            )
            candidate_metrics = _metric_names(candidate.get("result"))

            # Without an expected metric set, completeness cannot be proven.
            if expected and expected.issubset(candidate_metrics):
                chosen = candidate

        elif category != "financial" and not initial_ok and replan_ok:
            chosen = replan_ok[-1]


        if(category == 'research' and initial_ok and replan_ok):
            normalized[category] = {
                "task_types": entry["task_types"],
                #"plan_context": entry["plan_context"],
                #"tool": chosen.get("tool") if chosen else None,
                "tool_category": category,
                **(
                    {"tool": chosen["tool"]}
                    if chosen and "tool" in chosen else {}
                ),
                **(
                    {"tools": chosen["tools"]}
                    if chosen and "tools" in chosen else {}
                ),
                "result": [initial_ok[-1].get("result"), replan_ok[-1].get('result')],
            }

        else:
            normalized[category] = {
                "task_types": entry["task_types"],
                #"plan_context": entry["plan_context"],
                #"tool": chosen.get("tool") if chosen else None,
                "tool_category": category,
                **(
                    {"tool": chosen["tool"]}
                    if chosen and "tool" in chosen else {}
                ),
                **(
                    {"tools": chosen["tools"]}
                    if chosen and "tools" in chosen else {}
                ),
                "result": [chosen.get("result")] if chosen else [],
            }

    return normalized

#new report generation
def generate_final_report(
    *,
    user_query: str,
    thesis: Thesis,
    adjudication: Adjudication,
    research_plan: ResearchPlan,
    research_results: list[dict],
    replan_plan: ResearchPlan | None = None,
    financial_metrics: list[str] | None = None,
    replan_financial_metrics: list[str] | None = None,
) -> FinalReport:
    initial_results, replan_results = _split_results(research_results)

    initial_aligned = _align_results(initial_results, research_plan)
    replan_aligned = []

    if replan_results:
        if replan_plan is None:
            raise ValueError("Replan results exist without a replan plan.")

        replan_aligned = _align_results(replan_results, replan_plan)

    normalized = _normalize_results(
        initial_aligned,
        replan_aligned,
        financial_metrics,
        replan_financial_metrics,
    )

    summary, conclusion = _refine_report_narrative(
        user_query=user_query,
        thesis=thesis.thesis,
        conclusion=adjudication.rationale,
        normalized_results=list(normalized.values()),
        limitations=adjudication.evidence_debt,
    )

    return FinalReport(
        user_query=user_query,
        summary=summary,#earlier thesis.thesis(altered by LLM)
        thesis=thesis.thesis,
        conclusion=conclusion,#earlier adjudication.rationale(altered by LLM)
        confidence=adjudication.confidence,
        normalized_results=list(normalized.values()),
        limitations=adjudication.evidence_debt,
    )

